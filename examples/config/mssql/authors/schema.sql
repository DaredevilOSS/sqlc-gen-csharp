CREATE SEQUENCE authors_id_seq AS BIGINT START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE books_id_seq AS BIGINT START WITH 1 INCREMENT BY 1;

CREATE TABLE authors (
    id BIGINT NOT NULL PRIMARY KEY DEFAULT (NEXT VALUE FOR authors_id_seq),
    name NVARCHAR(255) NOT NULL,
    bio NVARCHAR(MAX)
);

CREATE TABLE books (
    id BIGINT NOT NULL PRIMARY KEY DEFAULT (NEXT VALUE FOR books_id_seq),
    name NVARCHAR(255) NOT NULL,
    author_id BIGINT NOT NULL,
    description NVARCHAR(MAX),
    FOREIGN KEY (author_id) REFERENCES authors (id) ON DELETE CASCADE
);
