using System.Text;

namespace MssqlSyntaxMatrix;

public static class MarkdownReport
{
    private static string Icon(Level level) => level switch
    {
        Level.Ok => "✅",
        Level.Minor => "🟡",
        Level.Mismatch => "🟠",
        Level.Dropped => "🕳️",
        Level.Error => "❌",
        Level.Panic => "💥",
        _ => "?"
    };

    private static string Icon(RunStatus status) => status switch
    {
        RunStatus.Ok => "✅",
        RunStatus.Error => "❌",
        RunStatus.Panic => "💥",
        _ => "–"
    };

    public static string Render(List<CaseResult> results, MatrixOptions options)
    {
        var builds = options.SqlcBuilds;
        var sb = new StringBuilder();
        sb.AppendLine("# SQL Server (mssql) syntax matrix");
        sb.AppendLine();
        sb.AppendLine("<!-- generated by end2end/MssqlSyntaxMatrix - do not edit -->");
        sb.AppendLine("Every case in [`cases/`](cases) is run through each sqlc build, the C# plugin, and SQL Server's own");
        sb.AppendLine("`sp_describe_undeclared_parameters` / `sp_describe_first_result_set`, which act as the oracle for what");
        sb.AppendLine("the parameter and result column types should be. See [README.md](README.md).");
        sb.AppendLine();
        foreach (var build in builds)
            sb.AppendLine($"- **{build.Name}**: {(build.Label == "" ? build.Path : build.Label)}");
        sb.AppendLine();
        sb.AppendLine("| Legend | |");
        sb.AppendLine("|---|---|");
        sb.AppendLine("| ✅ | matches SQL Server |");
        sb.AppendLine("| 🟡 | minor difference (sqlc is more conservative, or a compatible type of the same family) |");
        sb.AppendLine("| 🟠 | wrong or missing type, nullability, name or column count |");
        sb.AppendLine("| 🕳️ | the query is silently dropped from sqlc's output |");
        sb.AppendLine("| ❌ | sqlc fails |");
        sb.AppendLine("| 💥 | sqlc panics |");
        sb.AppendLine();

        sb.AppendLine("## Summary");
        sb.AppendLine();
        sb.AppendLine($"| | {string.Join(" | ", builds.Select(b => b.Name))} |");
        sb.AppendLine($"|---|{string.Concat(builds.Select(_ => "---|"))}");
        foreach (var level in Enum.GetValues<Level>())
            sb.AppendLine($"| {Icon(level)} {level} | {string.Join(" | ", builds.Select(b => results.Count(r => r.CaseLevel(b.Name) == level)))} |");
        sb.AppendLine($"| **cases** | {string.Join(" | ", builds.Select(_ => results.Count))} |");
        var pluginResults = results.Where(r => r.Sqlc[options.PluginBuild.Name].PluginStatus != RunStatus.Skipped).ToList();
        sb.AppendLine();
        sb.AppendLine($"C# plugin (on **{options.PluginBuild.Name}** output): {pluginResults.Count(r => r.Sqlc[options.PluginBuild.Name].PluginStatus == RunStatus.Ok)}/{pluginResults.Count} generate" +
                      (options.Compile ? $", {results.Count(r => r.CompileStatus == RunStatus.Ok)}/{pluginResults.Count} compile" : "") + ".");
        var invalid = results.Where(r => r.Oracle.SchemaError is not null).ToList();
        if (invalid.Count > 0)
            sb.AppendLine($"\n⚠️ {invalid.Count} case(s) have a schema SQL Server rejects: {string.Join(", ", invalid.Select(r => r.Case.Id))}");
        sb.AppendLine();

        foreach (var category in results.GroupBy(r => r.Case.Category))
        {
            sb.AppendLine($"## {category.Key}");
            sb.AppendLine();
            sb.AppendLine($"| Case | {string.Join(" | ", builds.Select(b => b.Name))} | plugin | compile | Notes |");
            sb.AppendLine($"|---|{string.Concat(builds.Select(_ => "---|"))}---|---|---|");
            foreach (var r in category)
            {
                var plugin = r.Sqlc[options.PluginBuild.Name];
                var note = Note(r, builds[^1].Name);
                sb.AppendLine($"| [{r.Case.Id[(r.Case.Id.IndexOf('/') + 1)..]}](cases/{r.Case.Id}.sql) {Escape(r.Case.Description)} | " +
                              $"{string.Join(" | ", builds.Select(b => Icon(r.CaseLevel(b.Name))))} | {Icon(plugin.PluginStatus)} | {Icon(r.CompileStatus)} | {Escape(note)} |");
            }
            sb.AppendLine();
        }

        sb.AppendLine("## Details");
        sb.AppendLine();
        foreach (var r in results)
        {
            var anyFinding = builds.Any(b => r.CaseLevel(b.Name) != Level.Ok)
                             || r.Sqlc[options.PluginBuild.Name].PluginStatus == RunStatus.Error
                             || r.CompileStatus == RunStatus.Error
                             || r.Oracle.SchemaError is not null;
            if (!anyFinding)
                continue;
            sb.AppendLine($"### {r.Case.Id}");
            sb.AppendLine();
            sb.AppendLine(r.Case.Description);
            sb.AppendLine();
            if (r.Oracle.SchemaError is not null)
                sb.AppendLine($"- ⚠️ SQL Server rejects the schema: `{r.Oracle.SchemaError}`");
            foreach (var build in builds)
            {
                var sqlc = r.Sqlc[build.Name];
                if (sqlc.Status is RunStatus.Error or RunStatus.Panic)
                {
                    sb.AppendLine($"- **{build.Name}** {Icon(r.CaseLevel(build.Name))}");
                    sb.AppendLine("  ```");
                    foreach (var line in sqlc.Error.Split('\n'))
                        sb.AppendLine($"  {line}");
                    sb.AppendLine("  ```");
                    continue;
                }
                foreach (var (query, verdict) in r.Verdicts(build.Name).Where(v => v.Verdict.Findings.Count > 0))
                    foreach (var f in verdict.Findings)
                        sb.AppendLine($"- **{build.Name}** `{query.Name}` {Icon(f.Level)} {Escape(f.Message)}");
            }
            var plugin = r.Sqlc[options.PluginBuild.Name];
            if (plugin.PluginStatus == RunStatus.Error)
                sb.AppendLine($"- **plugin** ❌ `{Escape(CaseResult.FirstLine(plugin.PluginError))}`");
            if (r.CompileStatus == RunStatus.Error)
                foreach (var line in r.CompileError.Split('\n'))
                    sb.AppendLine($"- **compile** ❌ `{Escape(line)}`");
            foreach (var (name, oracle) in r.Oracle.Queries)
            {
                if (oracle.ParamsError is not null)
                    sb.AppendLine($"- SQL Server, `{name}` parameters: {Escape(oracle.ParamsError)}");
                if (oracle.ColumnsError is not null)
                    sb.AppendLine($"- SQL Server, `{name}` result set: {Escape(oracle.ColumnsError)}");
            }
            sb.AppendLine();
        }
        return sb.ToString();
    }

    private static string Note(CaseResult r, string build)
    {
        var sqlc = r.Sqlc[build];
        if (sqlc.Status is RunStatus.Error or RunStatus.Panic)
            return r.Verdicts(build).First().Verdict.Findings.First().Message.Split('\n')[0];
        var finding = r.Verdicts(build).SelectMany(v => v.Verdict.Findings).OrderByDescending(f => f.Level).FirstOrDefault();
        if (finding is not null && finding.Level > Level.Minor)
            return finding.Message;
        if (sqlc.PluginStatus == RunStatus.Error)
            return "plugin: " + CaseResult.FirstLine(sqlc.PluginError);
        if (r.CompileStatus == RunStatus.Error)
            return "compile: " + CaseResult.FirstLine(r.CompileError);
        return finding?.Message ?? "";
    }

    private static string Escape(string text) => text.Replace("|", "\\|").Replace("\n", " ").Replace("\r", "");
}